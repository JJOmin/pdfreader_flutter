// Writes lib/shared/unicode_tables.dart from the Unicode Character Database, and copies Unicode's
// word and sentence break tests into test/unicode/. Run on the PC: dart run tool/gen_unicode.dart
//
// The version follows Node's ICU (`node -p process.versions.unicode`), because the segmenter must
// split like the desktop's Intl.Segmenter.
import 'dart:io';

const version = '17.0.0';
const base = 'https://www.unicode.org/Public/$version/ucd';

/// Property values in the order lib/shared/segment.dart's enums declare them.
const wordValues =
    ('Other CR LF Newline Extend ZWJ Regional_Indicator Format Katakana Hebrew_Letter ALetter '
    'Single_Quote Double_Quote MidNumLet MidLetter MidNum Numeric ExtendNumLet WSegSpace');
const sentenceValues =
    'Other CR LF Extend Sep Format Sp Lower Upper OLetter Numeric ATerm SContinue STerm Close';

Future<String> fetch(String path) async {
  final cache = File('tool/unicode/$version/${path.split('/').last}');
  if (!cache.existsSync()) {
    stdout.writeln('downloading $path');
    final client = HttpClient();
    final response = await (await client.getUrl(Uri.parse('$base/$path'))).close();
    if (response.statusCode != 200) throw StateError('$path: HTTP ${response.statusCode}');
    cache.parent.createSync(recursive: true);
    await response.pipe(cache.openWrite());
    client.close();
  }
  return cache.readAsString();
}

/// Parses "0041..005A ; ALetter # comment" lines into [start, end, value index] triples.
List<int> ranges(String data, List<String> values, {String? only}) {
  final triples = <List<int>>[];
  for (final line in data.split('\n')) {
    final content = line.split('#').first.trim();
    if (content.isEmpty) continue;
    final [codes, name] = content.split(';').map((s) => s.trim()).toList();
    if (only != null && name != only) continue;
    final value = only != null ? 1 : values.indexOf(name);
    if (value < 0) throw StateError('unknown property value $name');
    final bounds = codes.split('..').map((h) => int.parse(h, radix: 16)).toList();
    triples.add([bounds.first, bounds.last, value]);
  }
  triples.sort((a, b) => a[0] - b[0]);
  final merged = <List<int>>[];
  for (final t in triples) {
    final last = merged.isEmpty ? null : merged.last;
    if (last != null && last[2] == t[2] && last[1] + 1 == t[0]) {
      last[1] = t[1];
    } else {
      merged.add(t);
    }
  }
  return [for (final t in merged) ...t];
}

String table(String name, List<int> values) {
  final out = StringBuffer('const $name = <int>[\n');
  for (var i = 0; i < values.length; i += 12) {
    out.writeln('  ${values.skip(i).take(12).join(', ')},');
  }
  return (out..writeln('];')).toString();
}

Future<void> main() async {
  final word = ranges(await fetch('auxiliary/WordBreakProperty.txt'), wordValues.split(' '));
  final sentence = ranges(await fetch('auxiliary/SentenceBreakProperty.txt'), sentenceValues.split(' '));
  final pict = ranges(await fetch('emoji/emoji-data.txt'), const [], only: 'Extended_Pictographic');
  File('lib/shared/unicode_tables.dart').writeAsStringSync(
    '// Generated by tool/gen_unicode.dart from Unicode $version. Do not edit.\n'
    '// Each table is a flat list of [first code point, last code point, value] triples, sorted.\n'
    '// ignore_for_file: lines_longer_than_80_chars\n\n'
    "const unicodeVersion = '$version';\n\n"
    '${table('wordBreakRanges', word)}\n'
    '${table('sentenceBreakRanges', sentence)}\n'
    '${table('extendedPictographicRanges', pict)}',
  );
  Process.runSync('dart', ['format', 'lib/shared/unicode_tables.dart'], runInShell: true);
  for (final test in ['WordBreakTest.txt', 'SentenceBreakTest.txt']) {
    final data = await fetch('auxiliary/$test');
    File('test/unicode/$test')
      ..parent.createSync(recursive: true)
      ..writeAsStringSync(data);
  }
  stdout.writeln(
    'word ${word.length ~/ 3}, sentence ${sentence.length ~/ 3}, '
    'pictographic ${pict.length ~/ 3} ranges',
  );
}
